#pragma once

#include <memory>
#include <span>
#include <vector>

#include "Engine/Effects/Effect.h"

#include "airwin_consolidated_base.h"

namespace audium
{

class EffectRegistry;

namespace airwindows
{

/**
 * What the catalog knows about one Airwindows effect: its name, where it
 * goes in the insert menu, its parameters (Airwindows' own 0..1 values, so
 * a setting means what it means in any Airwindows host), and the functions
 * that create it, reset it and show its values. Generated by
 * ThirdParty/airwindows/audionaut/import_airwindows.py.
 */
struct AirwindowsDescriptor
{
    const char* name;
    const char* category;
    const char* description;
    std::span<const EffectParameterInfo> parameters;
    const char* const* labels;   ///< a unit per parameter ("dB", "sec"); the display text comes before it
    double tailSeconds;

    std::unique_ptr<AirwinConsolidatedBase> (*create)();

    /// Copies one instance's whole state over another of the same type: plain members only, nothing allocated.
    void (*copyState) (AirwinConsolidatedBase& to, const AirwinConsolidatedBase& from);

    /// The effect's own reading of a value ("-6.0000", "Nuke"); null when it has no parameters.
    void (*display) (int index, float value, char* text);

    /// Typed text back to a value, as the effect reads it; null when it has none.
    bool (*parse) (int index, const char* text, float& value);
};

/// Every effect of the catalog, in the order the insert menu lists them.
std::span<const AirwindowsDescriptor> getDescriptors() noexcept;

/// The type id an effect is stored under: "airwindows:" and its name in lower case.
std::string typeIdFor (const AirwindowsDescriptor& descriptor);

/// Registers the whole catalog.
void addEffects (EffectRegistry& registry);

/**
 * One Airwindows effect in an insert slot.
 *
 * Airwindows effects are stereo: a pair of channels runs through one
 * instance, a single channel through an instance whose right side is a
 * copy, folded back to mono as the average of the two (a stereo reverb on a
 * mono channel keeps both sides of its tail). Wider buses take an instance
 * per pair.
 *
 * Airwindows has no reset - an effect starts clean only when constructed -
 * so prepare() keeps a pristine instance beside each live one, and reset()
 * copies it over the live one: on the render thread, allocation-free, and
 * exact (the pristine copy has never processed anything). The parameters
 * are applied again after the copy.
 */
class AirwindowsEffect final : public Effect
{
public:
    explicit AirwindowsEffect (const AirwindowsDescriptor& descriptor);
    ~AirwindowsEffect() override;

    void prepare (double sampleRate, int maxBlockSize, int numChannels) override;
    void release() override;
    void reset() noexcept override;
    void process (juce::dsp::AudioBlock<float>& block) noexcept override;

    double getTailSeconds() const noexcept override;

    juce::String getParameterText (int index, float value) const override;
    bool parseParameterText (int index, const juce::String& text, float& value) const override;

    const AirwindowsDescriptor& getDescriptor() const noexcept { return descriptor; }

private:
    void applyParameters (AirwinConsolidatedBase& instance) const noexcept;

    const AirwindowsDescriptor& descriptor;
    std::vector<std::unique_ptr<AirwinConsolidatedBase>> live, pristine;   ///< one per channel pair
    std::vector<float> monoRight;   ///< the right side an odd last channel runs with
    int numChannels = 0;
};

} // namespace airwindows
} // namespace audium
